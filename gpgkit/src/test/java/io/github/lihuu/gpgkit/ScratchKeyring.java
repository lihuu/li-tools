package io.github.lihuu.gpgkit;

import org.junit.jupiter.api.Assumptions;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Comparator;
import java.util.List;
import java.util.concurrent.ThreadLocalRandom;
import java.util.stream.Stream;

/**
 * A throwaway keyring with one throwaway key, plus a scratch directory to sign files in.
 *
 * <p>The key matters. Whatever real key the person running these tests holds is their own: possibly
 * the only one they have, possibly the identity they sign releases with, possibly passphrase-less. A
 * test that generated a key in the default keyring — or signed with whatever key happened to be
 * there — would be a test that damages the thing it is supposed to protect. Every key here is
 * generated into a {@code GNUPGHOME} that is deleted at the end
 * of the test, and the key is disposable: ed25519 because it is instant, not because it is what anyone
 * would ship.
 *
 * <p>The fixture key is generated by calling gpg directly rather than by running {@code gpgkit gen}.
 * A fixture built out of the code under test turns one bug in {@code gen} into a red suite everywhere
 * else, and hides which command actually broke.
 */
final class ScratchKeyring implements AutoCloseable {
    /** Same short prefix as {@link TempDir}: a long path breaks gpg-agent's socket, quietly. */
    private static final String PREFIX = "gk-test-";

    private static final int ATTEMPTS = 32;

    private final Path root;
    private final Path home;
    private final Path work;
    private final String fingerprint;

    private ScratchKeyring(Path root, Path home, Path work, String fingerprint) {
        this.root = root;
        this.home = home;
        this.work = work;
        this.fingerprint = fingerprint;
    }

    static ScratchKeyring create() {
        Assumptions.assumeTrue(Gpg.locate().isPresent(),
                "gpg is not on PATH; these tests exercise the real GnuPG and skip without it");
        Path root = createRoot();
        Path home = root.resolve("gnupg");
        Path work = root.resolve("work");
        try {
            Files.createDirectory(home);
            Files.setPosixFilePermissions(home, PosixFilePermissions.fromString("rwx------"));
            Files.createDirectory(work);
        } catch (IOException failure) {
            throw new UncheckedIOException(failure);
        }
        return new ScratchKeyring(root, home, work, generate(home));
    }

    private static Path createRoot() {
        Path temporary = Path.of(System.getProperty("java.io.tmpdir"));
        for (int attempt = 0; attempt < ATTEMPTS; attempt++) {
            Path candidate = temporary.resolve(PREFIX + Long.toHexString(
                    ThreadLocalRandom.current().nextLong() & 0xFFFF_FFFFL));
            try {
                return Files.createDirectory(candidate);
            } catch (IOException taken) {
                // Somebody else's directory. Try another name.
            }
        }
        throw new IllegalStateException("could not find a free name for a test keyring in " + temporary);
    }

    /** @return the fingerprint gpg reports for the key it just made */
    private static String generate(Path home) {
        StringBuilder parameters = new StringBuilder();
        parameters.append("%no-protection\n");
        parameters.append("Key-Type: EDDSA\n");
        parameters.append("Key-Curve: ed25519\n");
        parameters.append("Key-Usage: sign\n");
        parameters.append("Subkey-Type: ECDH\n");
        parameters.append("Subkey-Curve: cv25519\n");
        parameters.append("Subkey-Usage: encrypt\n");
        parameters.append("Name-Real: Test Fixture\n");
        parameters.append("Name-Email: fixture@example.invalid\n");
        parameters.append("Expire-Date: 1y\n");
        parameters.append("%commit\n");

        try (TempDir scratch = TempDir.create()) {
            Path file = scratch.path().resolve("fixture.params");
            Files.writeString(file, parameters.toString(), StandardCharsets.UTF_8);
            Gpg.Result result = new Gpg(home).run(
                    List.of("--status-fd", "1", "--gen-key", file.toAbsolutePath().toString()));
            for (String line : result.out().split("\n")) {
                String marker = "[GNUPG:] KEY_CREATED ";
                if (line.startsWith(marker)) {
                    return line.substring(marker.length()).strip().split(" ")[1];
                }
            }
            throw new IllegalStateException("the test fixture key was not created: " + result.reason());
        } catch (IOException failure) {
            throw new UncheckedIOException(failure);
        }
    }

    /** The {@code GNUPGHOME} every command under test should see. */
    Path home() {
        return home;
    }

    /** A directory to write artifacts and signatures into. */
    Path work() {
        return work;
    }

    String fingerprint() {
        return fingerprint;
    }

    /** A CLI aimed at this keyring, working in {@link #work()}. */
    Cli cli() {
        return new Cli(work, home);
    }

    /** Writes a file into {@link #work()} and returns its path. */
    Path write(String name, String content) {
        try {
            Path file = work.resolve(name);
            Files.createDirectories(file.getParent());
            Files.writeString(file, content, StandardCharsets.UTF_8);
            return file;
        } catch (IOException failure) {
            throw new UncheckedIOException(failure);
        }
    }

    @Override
    public void close() {
        try (Stream<Path> entries = Files.walk(root)) {
            entries.sorted(Comparator.reverseOrder()).forEach(entry -> {
                try {
                    Files.deleteIfExists(entry);
                } catch (IOException ignored) {
                    // Best effort. A leftover temp directory is not worth failing a green test over.
                }
            });
        } catch (IOException ignored) {
            // Same.
        }
    }
}
